export type TeamText = (key: keyof typeof zh, vars?: Record<string, string | number>) => string;
export type TeamKey = keyof typeof zh;
/**
 * Team copy, with optional `{name}` interpolation — a code board has to say
 * "3 codes minted" and an import has to name the account it created.
 */
export const teamText =
  (locale: string): TeamText =>
  (key, vars) => {
    const raw = (locale.startsWith("zh") ? zh : en)[key];
    if (!vars || !raw) return raw;
    return raw.replace(/\{(\w+)\}/g, (match, name) =>
      name in vars ? String(vars[name as keyof typeof vars]) : match,
    );
  };
